"""D13 sanity checks of the wind-knowledge levels W0 / W1 / W2 (plan D13, 2026-10-03).

Per level: scene build time, the wind at the drone height at the 13 sources (W1/W0 versus the CFD wind W2: speed and
direction difference), the W1 potential-flow diagnostics on the real grid (divergence, calm courtyards, speeds), the
forward-model response ratio log10(g_level / g_W2) at +x centreline receptors 25 ... 400 m downwind of open sources,
and a synthetic-truth RB-PF run per level (truth = the level's own model, straight upwind flight from +250 m) that must
end within PF_SYNTH_MAX_ERR_M of the source: it checks the plumbing (Scene, RBPF, GMM) without any model mismatch.

Usage: python -m srcloc_env.scripts.validate_wind_levels [--levels W0 W1 W2] [--sources 108 111 101] [--steps 60]
Writes cache/eval/validate_wind_levels.json.
"""
from __future__ import annotations

import argparse
import json
import sys
import time

import numpy as np

from srcloc_env import config
from srcloc_env.env.source_env import Scene
from srcloc_env.field.wind_models import potential_flow_diagnostics
from srcloc_env.pf.lbm_adjoint import AdvectionDiffusionOperator
from srcloc_env.pf.particle_filter import RBPF
from srcloc_env.sensor.detector import Detector

RECEPTORS_M = (25.0, 50.0, 100.0, 200.0, 400.0)
PF_SYNTH_MAX_ERR_M = 30.0
OPEN_SOURCES = tuple(s for s in config.T1_3_OPEN_SOURCES if s != 101)   # 108/109/111/113: 101's 15 m plume lies mostly upwind (T1-3), so the +x flight is no valid path there


def synthetic_pf_run(scene: Scene, source: int, n_steps: int, seed: int = 0, n_particles: int = 2000) -> dict:
    """RB-PF fed with Poisson counts generated by the scene's OWN forward model along a straight upwind flight."""
    rng = np.random.default_rng(seed)
    det = Detector()
    xs, ys = scene.sources_xy[source]
    pf = RBPF(scene.model, n_particles=n_particles, obstacles=scene.obstacles, rng=np.random.default_rng(seed + 1),
              prior_x=config.PF_PRIOR_X, prior_y=config.PF_PRIOR_Y, eps_mix=config.PF_EPS_MIX, likelihood=config.PF_LIKELIHOOD,
              nb_r=config.PF_NB_DISPERSION_R, z=config.DRONE_Z, background=det.background, T=det.T, kappa_ref=config.KAPPA_REF)
    kappa_true = config.KAPPA_REF
    x = xs + config.PF_ADJ_START_DOWNWIND_M
    errs = []
    for t in range(n_steps):
        xy = np.array([x, ys])
        if not scene.obstacles.is_free(xy, config.DRONE_Z):                 # step around a building: shift sideways
            for dy in (20.0, -20.0, 40.0, -40.0, 60.0, -60.0):
                if scene.obstacles.is_free(np.array([x, ys + dy]), config.DRONE_Z):
                    xy = np.array([x, ys + dy]); break
        g = scene.model.unit_response(np.array([[xs, ys]]), np.array([[xy[0], xy[1], config.DRONE_Z]]))[0, 0]
        y = int(rng.poisson((kappa_true * g + det.background) * det.T))
        pf.update(y, np.array([xy[0], xy[1], config.DRONE_Z]))
        m = pf.map_estimate()
        errs.append(float(np.hypot(m[0] - xs, m[1] - ys)))
        x = max(x - config.DRONE_STEP_M, xs - 100.0)
    return {"final_error_m": errs[-1], "min_error_m": float(min(errs)), "error_at_half": errs[len(errs) // 2], "n_steps": n_steps}


def response_ratio(scene: Scene, ref: Scene, source: int) -> dict:
    """log10(g_level / g_W2) at +x centreline receptors; receptors inside a building (both adjoint models return the
    floor there) are reported as 'blocked' instead of a ratio (review D13)."""
    xs, ys = scene.sources_xy[source]
    rec = np.array([[xs + d, ys, config.DRONE_Z] for d in RECEPTORS_M])
    free = scene.obstacles.is_free(rec[:, :2], config.DRONE_Z, margin=0.0)
    g = scene.model.unit_response(np.array([[xs, ys]]), rec)[0]
    g0 = ref.model.unit_response(np.array([[xs, ys]]), rec)[0]
    return {f"{int(d)}m": (float(np.log10(g[i] / g0[i])) if free[i] else "blocked") for i, d in enumerate(RECEPTORS_M)}


def main(argv: list[str] | None = None) -> dict:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--levels", nargs="+", default=list(config.WIND_LEVELS))
    ap.add_argument("--sources", type=int, nargs="+", default=[108, 111, 101])
    ap.add_argument("--steps", type=int, default=60)
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="replace")
    scenes: dict[str, Scene] = {}
    out: dict = {"levels": {}, "U": config.WIND_MEAN_U, "dir_deg": config.WIND_MEAN_DIR_DEG}
    for lv in args.levels:
        t0 = time.perf_counter()
        sc = Scene.load(wind_level=lv)
        scenes[lv] = sc
        rec = {"build_s": time.perf_counter() - t0, "scene_build_s": sc.seconds_build, "model": type(sc.model).__name__}
        if lv == "W1":
            blocked = AdvectionDiffusionOperator.blocked_at_cells(sc.obstacles, sc.grid, config.DRONE_Z)
            rec["flow"] = potential_flow_diagnostics(sc.model.operator.uv, blocked, sc.grid.res, config.WIND_MEAN_U, config.WIND_MEAN_DIR_DEG)
        rec["wind_at_sources"] = {}
        for s, xy in sc.sources_xy.items():
            u, v = sc.wind.uv_at(np.array([xy]), config.DRONE_Z)[0]
            rec["wind_at_sources"][s] = {"u": float(u), "v": float(v), "speed": float(np.hypot(u, v)), "dir_deg": float(np.degrees(np.arctan2(v, u)))}
        rec["pf_synthetic"] = {s: synthetic_pf_run(sc, s, args.steps) for s in args.sources}
        out["levels"][lv] = rec
        print(f"[{lv}] build {rec['build_s']:.2f} s, model {rec['model']}; synthetic PF final error: " +
              ", ".join(f"{s} {r['final_error_m']:.0f} m" for s, r in rec["pf_synthetic"].items()) +
              (f"; flow div_rms {rec['flow']['div_rms']:.4f} (scale {rec['flow']['div_scale']:.3f}), speed mean {rec['flow']['speed_mean_free']:.2f} max {rec['flow']['speed_max_free']:.2f}" if lv == "W1" else ""), flush=True)
    if "W2" in scenes:
        for lv in args.levels:
            if lv == "W2":
                continue
            out["levels"][lv]["response_ratio_vs_W2"] = {s: response_ratio(scenes[lv], scenes["W2"], s) for s in args.sources}
            out["levels"][lv]["wind_vs_W2"] = {}
            for s in scenes[lv].sources_xy:
                a, b = out["levels"][lv]["wind_at_sources"][s], out["levels"]["W2"]["wind_at_sources"][s]
                dang = (a["dir_deg"] - b["dir_deg"] + 180.0) % 360.0 - 180.0
                out["levels"][lv]["wind_vs_W2"][s] = {"speed_ratio": a["speed"] / max(b["speed"], 1e-9), "angle_diff_deg": dang}
            print(f"[{lv} vs W2] log10 response ratio at +x receptors: " + "; ".join(f"{s}: " + " ".join(f"{k} {v:+.1f}" if isinstance(v, float) else f"{k} {v}" for k, v in out['levels'][lv]['response_ratio_vs_W2'][s].items()) for s in args.sources), flush=True)
    open_src = [s for s in args.sources if s in OPEN_SOURCES]
    if not open_src:
        raise SystemExit(f"--sources must include at least one open source {OPEN_SOURCES} for the synthetic PF pass rule")
    ok = all(lv["pf_synthetic"][s]["final_error_m"] < PF_SYNTH_MAX_ERR_M for lv in out["levels"].values() for s in open_src)
    out["pf_synthetic_pass"] = bool(ok)
    print(f"synthetic PF check (final error < {PF_SYNTH_MAX_ERR_M:.0f} m for every level at the open sources {open_src}; the straight +x flight is not a valid path for stagnant sources): {'PASS' if ok else 'FAIL'}")
    path = config.CACHE_DIR / "eval" / "validate_wind_levels.json"
    path.write_text(json.dumps(out, indent=2, default=lambda o: o.item() if hasattr(o, "item") else str(o)), encoding="utf-8")
    return out


if __name__ == "__main__":
    main()
